/* Bundles data/ and lib/standalone-template.html into lib/seed-data.js.
   The API imports that module directly, so Vercel always ships the data with the
   functions (reading data/ from disk at run time is not reliable there).
   Runs automatically on every Vercel deploy (buildCommand in vercel.json) and on npm run dev. */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const data = path.join(ROOT, "data");
const read = (p, fallback) => existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : fallback;

export function buildSeed() {
  const episodes = {};
  const dir = path.join(data, "episodes");
  for (const f of existsSync(dir) ? readdirSync(dir).sort() : []) {
    const m = /^ep0*(\d+)\.json$/.exec(f);
    if (!m) continue;
    const ep = read(path.join(dir, f));
    if (ep.num !== Number(m[1])) throw new Error(`${f}: "num" inside the file is ${ep.num}`);
    episodes[ep.num] = ep;
  }
  const seed = {
    topics: read(path.join(data, "topics.json"), {}),
    speakers: read(path.join(data, "speakers.json"), {}),
    known: read(path.join(data, "known.json"), []),
    episodes,
    template: readFileSync(path.join(ROOT, "lib", "standalone-template.html"), "utf8"),
  };
  const out = "/* Generated by scripts/build-seed.mjs from data/ — edit the files in data/, not this one. */\n"
    + "export default JSON.parse(" + JSON.stringify(JSON.stringify(seed)) + ");\n";
  writeFileSync(path.join(ROOT, "lib", "seed-data.js"), out);
  buildContent();
  return Object.keys(episodes).map(Number);
}

/* Series pages that are single self-contained HTML files: content/<lang>/<slug>.html.
   They are served by api/content.js only after login. Inline scripts are moved out
   (served as /api/content?...&part=js) because the site's security policy forbids inline
   scripts, and a "← Все сериалы" link is added at the top. The home page (public/index.html)
   is bundled too: it is shown for series that have no content yet. */
export function buildContent() {
  const pages = {};
  const dir = path.join(ROOT, "content");
  for (const lang of existsSync(dir) ? readdirSync(dir).sort() : []) {
    if (!/^[a-z]{2}$/.test(lang)) continue;
    for (const f of readdirSync(path.join(dir, lang)).sort()) {
      const m = /^([a-z0-9-]+)\.html$/.exec(f);
      if (!m) continue;
      const slug = m[1], id = lang + "/" + slug;
      let html = readFileSync(path.join(dir, lang, f), "utf8");
      const scripts = [];
      html = html.replace(/<script(\s[^>]*)?>([\s\S]*?)<\/script>/gi, (all, attrs = "", code) => {
        if (/\bsrc\s*=/.test(attrs)) return all;
        scripts.push(code);
        return '<script src="/api/content?id=' + encodeURIComponent(id) + '&part=js&n=' + (scripts.length - 1) + '"></script>';
      });
      const back = '<a href="/#' + lang + '" style="display:block;padding:7px 20px;background:#111;color:#fff;font:600 14px/1.4 system-ui,-apple-system,sans-serif;text-decoration:none">← Все сериалы</a>';
      html = html.replace(/<body([^>]*)>/i, (b) => b + back);
      const title = (/<title>([\s\S]*?)<\/title>/i.exec(html) || [])[1] || slug;
      pages[id] = { lang, slug, title: title.trim(), html, scripts };
    }
  }
  const landing = readFileSync(path.join(ROOT, "public", "index.html"), "utf8");
  const out = "/* Generated by scripts/build-seed.mjs from content/ — edit the files in content/, not this one. */\n"
    + "export default JSON.parse(" + JSON.stringify(JSON.stringify({ pages, landing })) + ");\n";
  writeFileSync(path.join(ROOT, "lib", "content-data.js"), out);
  return Object.keys(pages);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log("Bundled episodes:", buildSeed().join(", ") || "none");
  console.log("Bundled series pages:", Object.keys((await import("../lib/content-data.js?" + Date.now())).default.pages).join(", ") || "none");
}
