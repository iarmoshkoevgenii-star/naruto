/* Bundles the repository content into lib/seed-data.js, which the API imports directly
   (reading files from disk at run time is not reliable on Vercel):
   - data/                       Naruto episodes, topics, speakers, known words
   - content/en/<slug>.html      English episodes: the "const DATA = {...}" block of each page
   - content/en/<slug>.meta.json title and hero text for that episode (optional)
   - lib/standalone-template.html the single-file Naruto site used by export
   Runs on every Vercel deploy (buildCommand in vercel.json) and on npm run dev. */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const data = path.join(ROOT, "data");
const read = (p, fallback) => existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : fallback;

function english() {
  const out = {};
  const dir = path.join(ROOT, "content", "en");
  for (const f of existsSync(dir) ? readdirSync(dir).sort() : []) {
    const m = /^([a-z0-9-]+)\.html$/.exec(f);
    if (!m) continue;
    const html = readFileSync(path.join(dir, f), "utf8");
    const d = /const DATA = (\{[\s\S]*?\});\n/.exec(html);
    if (!d) throw new Error(`content/en/${f}: no "const DATA = {...};" block found`);
    const doc = JSON.parse(d[1]);
    const info = read(path.join(dir, m[1] + ".meta.json"), null) || { title: (/<title>([^<—]+)/.exec(html) || [, m[1]])[1].trim() };
    out[m[1]] = { info, ...doc };
  }
  return out;
}

export function buildSeed() {
  const episodes = {};
  const dir = path.join(data, "episodes");
  for (const f of existsSync(dir) ? readdirSync(dir).sort() : []) {
    const m = /^ep0*(\d+)\.json$/.exec(f);
    if (!m) continue;
    const ep = read(path.join(dir, f));
    if (ep.num !== Number(m[1])) throw new Error(`${f}: "num" inside the file is ${ep.num}`);
    episodes[ep.num] = ep;
  }
  const seed = {
    topics: read(path.join(data, "topics.json"), {}),
    speakers: read(path.join(data, "speakers.json"), {}),
    known: read(path.join(data, "known.json"), []),
    episodes,
    english: english(),
    template: readFileSync(path.join(ROOT, "lib", "standalone-template.html"), "utf8"),
  };
  const out = "/* Generated by scripts/build-seed.mjs from data/ and content/ — edit those, not this file. */\n"
    + "export default JSON.parse(" + JSON.stringify(JSON.stringify(seed)) + ");\n";
  writeFileSync(path.join(ROOT, "lib", "seed-data.js"), out);
  return { naruto: Object.keys(episodes).map(Number), english: Object.keys(seed.english) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = buildSeed();
  console.log("Naruto episodes:", r.naruto.join(", ") || "none");
  console.log("English episodes:", r.english.join(", ") || "none");
}
